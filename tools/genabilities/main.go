//go:build ignore

// genabilities writes internal/gamedata/abilities_gen.go from sc2reader's
// per-build ability tables (MIT; see third_party/sc2reader/LICENSE).
// Only the handful of abilities the command tier needs are extracted.
//
//	git clone https://github.com/ggtracker/sc2reader /tmp/sc2reader
//	go run tools/genabilities/main.go /tmp/sc2reader > internal/gamedata/abilities_gen.go
package main

import (
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

// The ability names we need, as sc2reader spells them, and the semantic
// name they map to (redirect variants share their base ability's meaning).
var wanted = map[string]string{
	"move": "move", "attack": "attack", "stop": "stop",
	"AttackRedirect": "attack",
	"Stimpack":       "stim", "StimpackMarauder": "stim",
	"StimpackRedirect": "stim", "StimpackMarauderRedirect": "stim",
	"MedivacSpeedBoost": "speedboost",
	"Rally":             "rally", "RallyCommand": "rally-workers", "RallyNexus": "rally-workers",
	"RallyHatchery": "rally-hatchery",
}

// First builds of sc2reader's LotV datapacks (resources.py); "base" covers
// 34784 up to the first numbered pack. 89720 starts at 89634.
var starts = map[string]int{"base": 34784, "89720": 89634, "96883": 95122}

func main() {
	dir := filepath.Join(os.Args[1], "sc2reader", "data", "LotV")
	files, _ := filepath.Glob(filepath.Join(dir, "*_abilities.csv"))
	type pack struct {
		from  int
		links map[int]string
	}
	var packs []pack
	for _, f := range files {
		name := strings.TrimSuffix(filepath.Base(f), "_abilities.csv")
		from, ok := starts[name]
		if !ok {
			from, _ = strconv.Atoi(name)
		}
		p := pack{from: from, links: map[int]string{}}
		fh, err := os.Open(f)
		if err != nil {
			panic(err)
		}
		sc := bufio.NewScanner(fh)
		for sc.Scan() {
			parts := strings.SplitN(sc.Text(), ",", 2)
			if len(parts) != 2 {
				continue
			}
			if sem, ok := wanted[strings.TrimSpace(parts[1])]; ok {
				id, err := strconv.Atoi(parts[0])
				if err == nil {
					p.links[id] = sem
				}
			}
		}
		fh.Close()
		packs = append(packs, p)
	}
	sort.Slice(packs, func(i, j int) bool { return packs[i].from < packs[j].from })
	fmt.Println("// Code generated by tools/genabilities from sc2reader's ability tables (MIT,")
	fmt.Println("// see third_party/sc2reader/LICENSE). DO NOT EDIT.")
	fmt.Println()
	fmt.Println("package gamedata")
	fmt.Println()
	fmt.Println("var abilityPacks = []abilityPack{")
	for _, p := range packs {
		ids := make([]int, 0, len(p.links))
		for id := range p.links {
			ids = append(ids, id)
		}
		sort.Ints(ids)
		fmt.Printf("\t{from: %d, links: map[int64]string{", p.from)
		for i, id := range ids {
			if i > 0 {
				fmt.Print(", ")
			}
			fmt.Printf("%d: %q", id, p.links[id])
		}
		fmt.Println("}},")
	}
	fmt.Println("}")
}
